package com.sgtesting.Pojo.Serialization;

public class Location {
    private double lat;
    private double lon;

    public double getLat() {
        return lat;
    }

    public void setLat(double lat) {
        this.lat = lat;
    }

    public double getLon() {
        return lon;
    }

    public void setLng(double lon) {
        this.lon = lon;
    }
}
